# --- Lazy initialization ---
# All CrewAI objects are created on first call to run_crew(),
# NOT at import time. This prevents crashes on Render startup.

_crew = None


def _build_crew():
    """Build all CrewAI objects. Called once on first request."""
    from crewai import LLM, Agent, Task, Crew
    from crewai.tools import tool
    from pptx import Presentation
    from pptx.util import Inches, Pt
    from pptx.dml.color import RGBColor
    import requests

    gemini_llm = LLM(
        model="gemini/gemini-2.5-flash",
        api_key=os.getenv("GEMINI_API_KEY"),
        use_native=False
    
    )

    # --- Tools ---
    def get_topic_image(topic: str, save_path: str) -> str:
        """Fetches a relevant image from Unsplash"""
        url = f"https://source.unsplash.com/800x400/?{topic.replace(' ', ',')}"
        try:
            response = requests.get(url, timeout=10)
            if response.status_code == 200:
                with open(save_path, "wb") as f:
                    f.write(response.content)
                return save_path
        except Exception:
            pass
        return None

    @tool()
    def create_presentation(content: str) -> str:
        """
        Creates a PowerPoint presentation from the study plan content.
        Input should be the full study plan text.
        Returns the path to the saved presentation file.
        """
        prs = Presentation()
        prs.slide_width = Inches(13.33)
        prs.slide_height = Inches(7.5)

        slide_layout = prs.slide_layouts[0]
        slide = prs.slides.add_slide(slide_layout)
        title = slide.shapes.title
        subtitle = slide.placeholders[1]
        title.text = "Your Personalized Study Plan"
        subtitle.text = "Generated by AI Course Planner"

        sections = content.split("##")

        for section in sections:
            if not section.strip():
                continue

            slide_layout = prs.slide_layouts[1]
            slide = prs.slides.add_slide(slide_layout)

            lines = section.strip().split("\n")
            slide.shapes.title.text = lines[0].strip()

            body = slide.placeholders[1]
            body.text = "\n".join(lines[1:]).strip()[:500]

            img_path = get_topic_image(
                "learning education",
                os.path.join(tempfile.gettempdir(), "slide_image.jpg"),
            )
            if img_path:
                slide.shapes.add_picture(
                    img_path,
                    Inches(8),
                    Inches(2),
                    Inches(4),
                    Inches(3),
                )

        output_path = os.path.join(tempfile.gettempdir(), "study_plan_presentation.pptx")
        prs.save(output_path)
        return f"Presentation saved to {output_path}"

    # --- Agents ---
    user_intake_agent = Agent(
        role="Student Intake Specialist",
        goal=(
            "Interact with the user and collect EXACTLY four pieces of information.\n"
            "  1. WHAT  — the topic or subject the user wants to study\n"
            "  2. WHY   — the user's motivation or goal for studying this\n"
            "  3. LEVEL — how deep they want to go (beginner / intermediate / "
            "advanced / mastery)\n"
            "  4. TYPE  — whether they prefer free courses, paid courses, or both\n\n"
            "If any answer is missing, vague, or unclear, ask a polite follow-up "
            "question using the 'Ask User' tool until you have a concrete answer.\n"
            "Once ALL FOUR answers are collected, compile them into a structured "
            "student profile summary."
        ),
        backstory=(
            "You are a friendly, patient academic counselor who has helped "
            "thousands of students begin their learning journeys. You guide "
            "students step-by-step through a short intake questionnaire. You "
            "never rush — you make sure every answer is specific and useful "
            "before moving to the next question. You are warm and encouraging."
        ),
        llm=gemini_llm,
        verbose=True,
        allow_delegation=False,
        max_iter=25,
    )

    agenmt_researcher_agent = Agent(
        role="Learning Goal Researcher",
        goal=(
            "Receive the student profile from Agent 1 (topic, motivation, level, "
            "course type). Focus on:\n"
            "  • The student's MOTIVATION (WHY they are studying)\n"
            "  • The student's desired LEVEL\n\n"
            "Then research and produce a detailed strategy for how the student "
            "can achieve that goal. Include:\n"
            "  • Key milestones to reach\n"
            "  • Core skills and sub-topics to master\n"
            "  • Estimated timeframes for each phase\n"
            "  • Recommended learning approaches (project-based, theory-first, etc.)\n"
            "  • Common pitfalls to avoid\n\n"
            "CRITICAL: You MUST forward ALL original student profile data "
            "(topic, motivation, level, course type) alongside your research "
            "so that the next agent has everything it needs."
        ),
        backstory=(
            "You are an expert educational strategist with deep knowledge of "
            "learning science, skill acquisition frameworks, and career pathways "
            "across dozens of fields. You excel at translating a student's "
            "motivation into a practical, achievable roadmap with clear milestones."
        ),
        llm=gemini_llm,
        verbose=True,
        allow_delegation=False,
    )

    prompt_engineer_agent = Agent(
        role="Prompt Engineer",
        goal=(
            "Take ALL information from Agent 2 — which includes the original "
            "student profile AND the goal-achievement research strategy — and "
            "synthesize it into the single BEST, most detailed prompt possible.\n\n"
            "This prompt will be given to Agent 4 to generate a personalized "
            "study plan and course recommendations. It MUST include:\n"
            "  • The topic, motivation, and level\n"
            "  • Free vs. paid preference\n"
            "  • The milestones and timeframes from the research\n"
            "  • The recommended learning approach\n"
            "  • Clear output format instructions (study plan + courses + resources)\n\n"
            "The prompt must be 300-600 words, structured, and highly actionable."
        ),
        backstory=(
            "You are a world-class prompt engineer who specializes in writing "
            "precise, detailed instructions for AI systems. You know exactly "
            "what context, constraints, and formatting instructions to include "
            "so the downstream agent produces the highest-quality output possible."
        ),
        llm=gemini_llm,
        verbose=True,
        allow_delegation=False,
    )

    course_planner_agent = Agent(
        role="Personalized Course Planner",
        goal=(
            "Using the optimized prompt from Agent 3, generate a COMPREHENSIVE "
            "personalized study plan AND a curated list of course recommendations "
            "with links.\n\n"
            "Your output MUST include:\n"
            "  • 📋 STUDY PLAN — A week-by-week or phase-by-phase plan with:\n"
            "      - Phase name and duration\n"
            "      - Specific topics to cover per phase\n"
            "      - Learning objectives\n"
            "      - Practice exercises or projects\n\n"
            "  • 🎓 COURSE RECOMMENDATIONS — A curated list with:\n"
            "      - Course name\n"
            "      - Platform (Coursera, Udemy, edX, YouTube, freeCodeCamp, etc.)\n"
            "      - Direct URL / link to the course\n"
            "      - FREE or PAID label (matching user preference)\n"
            "      - Brief description\n\n"
            "  • 📚 SUPPLEMENTARY RESOURCES — Books, YouTube channels, tools, "
            "communities\n\n"
            "  • 💡 TIPS — Practical advice for staying motivated and on track"
        ),
        backstory=(
            "You are an elite learning designer who has helped thousands of "
            "students achieve their study goals. You have encyclopedic knowledge "
            "of every major MOOC platform — Coursera, edX, Udemy, Udacity, "
            "Khan Academy, freeCodeCamp, MIT OpenCourseWare, YouTube educators, "
            "Codecademy, LinkedIn Learning, Pluralsight — and always recommend "
            "the best courses with working links."
        ),
        llm=gemini_llm,
        tools=[create_presentation],
        verbose=True,
        allow_delegation=False,
    )

    # --- Tasks ---
    intake_task = Task(
        description=(
            "The student has provided the following information:\n"
            "- Topic: {topic}\n"
            "- Motivation: {motivation}\n"
            "- Level: {level}\n"
            "- Course type preference: {course_type}\n\n"
            "Compile this into a clean, structured student profile summary."
        ),
        expected_output="A structured student profile with topic, motivation, level and course type.",
        agent=user_intake_agent,
    )

    research_task = Task(
        description="Research a learning strategy based on the student profile.",
        expected_output="A detailed learning roadmap with milestones and timeframes.",
        agent=agenmt_researcher_agent,
        context=[intake_task],
    )

    prompt_task = Task(
        description="Synthesize all information into one optimized prompt for the course planner.",
        expected_output="A 300-600 word structured prompt.",
        agent=prompt_engineer_agent,
        context=[research_task],
    )

    planning_task = Task(
        description="Generate a personalized study plan and course recommendations.",
        expected_output="A full study plan with course links, resources and tips.",
        agent=course_planner_agent,
        context=[prompt_task],
    )

    crew = Crew(
        agents=[user_intake_agent, agenmt_researcher_agent, prompt_engineer_agent, course_planner_agent],
        tasks=[intake_task, research_task, prompt_task, planning_task],
        verbose=True,
    )

    return crew


def write_report_guardrail(output):
    try:
        output = output if type(output) == str else output.raw
    except Exception as e:
        return (False, f"Error retrieving the raw argument:\n{str(e)}\n")
    output_lower = output.lower()

    if not re.search(r"study plan", output_lower):
        return (False, "Missing study plan section.")

    if not re.search(r"course recommendations", output_lower):
        return (False, "Missing course recommendations section.")

    return (True, "Report passed guardrail checks.")


def save_file_hook(result, topic="study_plan"):
    """
    Save the final research report to a local markdown file.
    Uses temp directory on deployed environments (e.g. Render).
    """
    try:
        # Get the final report content from the last task output
        if hasattr(result, 'tasks_output') and result.tasks_output:
            report_content = result.tasks_output[-1].raw
        else:
            report_content = str(result)

        filename = f"study_plan_{topic.replace(' ', '_')}.md"
        filepath = os.path.join(tempfile.gettempdir(), filename)

        # Save to file
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(report_content)

        print(f"Report successfully saved to: {filepath}")

    except Exception as e:
        print(f"Error saving report to file: {str(e)}")


def run_crew(topic, motivation, level, course_type):
    """Run the CrewAI pipeline and return the final study plan as a string.

    NOTE: We intentionally build a fresh Crew on every request.
    Reusing a cached crew causes stale task outputs from previous runs
    to bleed into the next run's context, which breaks agent 3+.
    """
    crew = _build_crew()

    result = crew.kickoff(inputs={
        "topic": topic,
        "motivation": motivation,
        "level": level,
        "course_type": course_type
    })
    save_file_hook(result, topic=topic)

    # Extract the raw markdown content
    if hasattr(result, 'tasks_output') and result.tasks_output:
        return result.tasks_output[-1].raw
    return str(result)


